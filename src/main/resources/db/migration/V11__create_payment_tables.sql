-- Card payments through Stripe PaymentIntents (C-PAY-01/02), refunds on cancellation (C-PAY-05) and the log of Stripe
-- webhook events. Table and column names follow DATABASE-SCHEMA.md; ids, version and audit timestamps follow this
-- project (see V2), and enum-like columns hold the Java enum names. Money is in minor units of the ISO 4217 currency,
-- like bookings.

-- One PaymentIntent per booking. Stripe's state decides the status: a declined card is FAILED and can be retried on
-- the same intent until the hold ends, when the intent is canceled.
create table payments (
    id                         bigint generated by default as identity primary key,
    booking_id                 bigint       not null references bookings (id),
    provider                   varchar(20)  not null default 'stripe',
    stripe_payment_intent_id   varchar(255) unique,
    stripe_checkout_session_id varchar(255) unique, -- in the schema doc; the PaymentIntent integration leaves it null
    amount_minor               bigint       not null check (amount_minor >= 0),
    currency                   varchar(3)   not null check (currency ~ '^[A-Z]{3}$'),
    status                     varchar(20)  not null default 'REQUIRES_PAYMENT'
        check (status in ('REQUIRES_PAYMENT', 'PROCESSING', 'SUCCEEDED', 'FAILED', 'CANCELED')),
    failure_reason             varchar(500), -- the decline message Stripe gives for the customer
    paid_at                    timestamptz,
    version                    bigint       not null default 0,
    created_at                 timestamptz  not null,
    updated_at                 timestamptz  not null,
    check (status <> 'SUCCEEDED' or paid_at is not null)
);

create unique index one_successful_payment on payments (booking_id) where status = 'SUCCEEDED';
-- Not in the schema doc: at most one payment per booking that the customer can still complete. The payment start
-- locks the booking row first; this index is the backstop.
create unique index one_open_payment on payments (booking_id) where status in ('REQUIRES_PAYMENT', 'PROCESSING', 'FAILED');
create index payments_booking_id_idx on payments (booking_id);

-- A refund is written with the cancellation and sent to Stripe after it commits; until Stripe answers it has no
-- stripe_refund_id.
create table refunds (
    id               bigint generated by default as identity primary key,
    payment_id       bigint       not null references payments (id),
    booking_id       bigint       not null references bookings (id),
    stripe_refund_id varchar(255) unique,
    amount_minor     bigint       not null check (amount_minor > 0),
    currency         varchar(3)   not null check (currency ~ '^[A-Z]{3}$'),
    reason           varchar(500),
    status           varchar(10)  not null default 'PENDING' check (status in ('PENDING', 'SUCCEEDED', 'FAILED')),
    initiated_by     bigint references users (id), -- null = the system
    version          bigint       not null default 0,
    created_at       timestamptz  not null,
    updated_at       timestamptz  not null
);

create index refunds_booking_id_idx on refunds (booking_id);
-- Not in the schema doc: refunds still to send to Stripe, read by the retry job.
create index refunds_unsent on refunds (created_at) where stripe_refund_id is null and status = 'PENDING';

-- Every Stripe webhook event once, by its id (the idempotency key). Written once and never versioned, like
-- booking_status_history.
create table stripe_events (
    id           varchar(255)  primary key, -- evt_...
    type         varchar(100)  not null,
    payload      jsonb         not null,
    received_at  timestamptz   not null default now(),
    processed_at timestamptz,
    error        varchar(1000)
);
