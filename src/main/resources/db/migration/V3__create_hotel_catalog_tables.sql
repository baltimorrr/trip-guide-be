-- The business behind one or more hotels.
create table partners (
    id              bigint generated by default as identity primary key,
    legal_name      varchar(200)  not null,
    tax_id          varchar(50),
    contact_email   varchar(254)  not null, -- stored lowercased, like users.email
    phone           varchar(30),
    commission_rate numeric(5, 2) not null default 15.00 check (commission_rate between 0 and 100),
    status          varchar(20)   not null default 'PENDING' check (status in ('PENDING', 'APPROVED', 'SUSPENDED')),
    approved_by     bigint references users (id),
    approved_at     timestamptz,
    deleted_at      timestamptz,
    version         bigint        not null default 0,
    created_at      timestamptz   not null,
    updated_at      timestamptz   not null
);

-- Structured address; fields follow Google Places address components.
create table addresses (
    id              bigint generated by default as identity primary key,
    line1           varchar(200) not null, -- house number + street
    line2           varchar(200),
    ward            varchar(100),
    district        varchar(100),          -- not every country has one
    city            varchar(100) not null,
    state_province  varchar(100),
    postal_code     varchar(20),
    country_code    varchar(2)   not null check (country_code ~ '^[A-Z]{2}$'),
    latitude        numeric(9, 6) check (latitude between -90 and 90),
    longitude       numeric(9, 6) check (longitude between -180 and 180),
    google_place_id varchar(255),
    formatted       varchar(500),
    verified_at     timestamptz,
    version         bigint       not null default 0,
    created_at      timestamptz  not null,
    updated_at      timestamptz  not null,
    check ((latitude is null) = (longitude is null))
);

-- Finds the hotels inside a destination. Queries must repeat these exact expressions to use it.
create index addresses_place_match on addresses (country_code, coalesce(norm(state_province), ''),
    coalesce(norm(city), ''), coalesce(norm(district), ''), coalesce(norm(ward), ''));

create table hotels (
    id                    bigint generated by default as identity primary key,
    partner_id            bigint       not null references partners (id),
    accommodation_type_id bigint       not null references accommodation_types (id),
    name                  varchar(200) not null,
    slug                  varchar(220) not null,
    description           text,
    star_rating           smallint check (star_rating between 1 and 5),
    address_id            bigint       not null references addresses (id),
    distance_to_center_m  integer,
    google_place_id       varchar(255),
    google_rating         numeric(2, 1) check (google_rating between 0 and 5),
    google_rating_count   integer,
    google_synced_at      timestamptz,
    user_rating_avg       numeric(3, 1) check (user_rating_avg between 0 and 10),
    user_rating_count     integer      not null default 0,
    currency              varchar(3)   not null check (currency ~ '^[A-Z]{3}$'), -- selling currency
    timezone              varchar(50)  not null,
    check_in_from         time         not null default '14:00',
    check_in_until        time,
    check_out_until       time         not null default '12:00',
    min_check_in_age      smallint default 18,
    phone                 varchar(30),
    email                 varchar(254),
    status                varchar(20)  not null default 'DRAFT'
        check (status in ('DRAFT', 'PENDING_REVIEW', 'ACTIVE', 'INACTIVE', 'SUSPENDED')),
    deleted_at            timestamptz,
    version               bigint       not null default 0,
    created_at            timestamptz  not null,
    updated_at            timestamptz  not null,
    constraint uk_hotels_slug unique (slug),
    constraint uk_hotels_address_id unique (address_id),
    constraint uk_hotels_google_place_id unique (google_place_id)
);

create index hotels_partner_id_idx on hotels (partner_id);
-- Hotel-name autocomplete: word-prefix LIKE on the normalized name of listed hotels.
create index hotels_name_search on hotels using gin (norm(name) gin_trgm_ops)
    where status = 'ACTIVE' and deleted_at is null;

create table room_types (
    id            bigint generated by default as identity primary key,
    hotel_id      bigint       not null references hotels (id) on delete cascade,
    name          varchar(150) not null,
    description   text,
    size_sqm      numeric(6, 1),
    max_adults    smallint     not null check (max_adults >= 1),
    max_children  smallint     not null default 0 check (max_children >= 0),
    max_occupancy smallint     not null,
    total_rooms   smallint     not null check (total_rooms >= 0), -- default rooms sold per night
    status        varchar(20)  not null default 'DRAFT'
        check (status in ('DRAFT', 'PENDING_REVIEW', 'ACTIVE', 'INACTIVE', 'SUSPENDED')),
    sort_order    smallint     not null default 0,
    deleted_at    timestamptz,
    version       bigint       not null default 0,
    created_at    timestamptz  not null,
    updated_at    timestamptz  not null,
    check (max_occupancy >= max_adults)
);

create index room_types_hotel_id_idx on room_types (hotel_id) where deleted_at is null;

create table hotel_photos (
    id           bigint generated by default as identity primary key,
    hotel_id     bigint       not null references hotels (id) on delete cascade,
    room_type_id bigint references room_types (id) on delete cascade, -- null = hotel photo
    url          varchar(500) not null,
    category     varchar(30),                                         -- room, pool, lobby, exterior...
    caption      varchar(200),
    sort_order   smallint     not null default 0,
    is_cover     boolean      not null default false,
    version      bigint       not null default 0,
    created_at   timestamptz  not null,
    updated_at   timestamptz  not null
);

create index hotel_photos_hotel_id_sort_order_idx on hotel_photos (hotel_id, sort_order);
create unique index one_cover_per_hotel on hotel_photos (hotel_id) where is_cover and room_type_id is null;

-- Rooms per room type per night, shared by all rate plans. Written only by set-based SQL, so it keeps
-- the schema's composite key (like user_roles). A missing row means room_types.total_rooms, none
-- booked, open for sale.
create table room_inventory (
    room_type_id bigint      not null references room_types (id) on delete cascade,
    stay_date    date        not null,
    total_rooms  smallint    not null check (total_rooms >= 0),
    booked_rooms smallint    not null default 0 check (booked_rooms >= 0), -- pending + confirmed
    is_closed    boolean     not null default false,                       -- stop-sell
    updated_at   timestamptz not null default now(),
    primary key (room_type_id, stay_date),
    check (booked_rooms <= total_rooms)
);

create index room_inventory_stay_date_idx on room_inventory (stay_date);

-- Places travellers search and browse: country, city, district, ward. Synced from the addresses of
-- active hotels (no foreign key between them); the level a place belongs to is read from its keys.
-- The keys are generated from the stored spellings, so every spelling that normalizes alike is one place.
-- Admins own name, image_url and featured_rank, which the sync never overwrites.
create table destinations (
    id              bigint generated by default as identity primary key,
    type            varchar(20)  not null check (type in ('COUNTRY', 'CITY', 'DISTRICT', 'WARD')),
    name            varchar(150) not null, -- display name, e.g. "Đà Nẵng"
    normalized_name text generated always as (norm(name)) stored check (normalized_name <> ''),
    slug            varchar(200) not null, -- vn-da-nang
    country_code    varchar(2)   not null check (country_code ~ '^[A-Z]{2}$'),
    -- Most common spelling of each address part among the place's hotels; null below the place's level.
    state_province  varchar(100),
    city            varchar(100),
    district        varchar(100),
    ward            varchar(100),
    province_key    text generated always as (coalesce(norm(state_province), '')) stored,
    city_key        text generated always as (coalesce(norm(city), '')) stored,
    district_key    text generated always as (coalesce(norm(district), '')) stored,
    ward_key        text generated always as (coalesce(norm(ward), '')) stored,
    source          varchar(10)  not null default 'SYNC' check (source in ('SYNC', 'ADMIN')),
    hotel_count     integer      not null default 0 check (hotel_count >= 0), -- active hotels here
    last_synced_at  timestamptz,
    google_place_id varchar(255),
    center_lat      numeric(9, 6),
    center_lng      numeric(9, 6),
    timezone        varchar(50),
    image_url       varchar(500),
    featured_rank   smallint, -- not null = shown on the homepage, lowest first
    deleted_at      timestamptz,
    version         bigint       not null default 0,
    created_at      timestamptz  not null,
    updated_at      timestamptz  not null,
    constraint uk_destinations_slug unique (slug),
    constraint uk_destinations_google_place_id unique (google_place_id),
    check (type <> 'COUNTRY' or (province_key = '' and city_key = '' and district_key = '' and ward_key = '')),
    check (type <> 'CITY' or (city_key <> '' and district_key = '' and ward_key = '')),
    check (type <> 'DISTRICT' or (city_key <> '' and district_key <> '' and ward_key = '')),
    check (type <> 'WARD' or (city_key <> '' and ward_key <> ''))
);

create unique index destination_place_key on destinations
    (country_code, province_key, city_key, district_key, ward_key) where deleted_at is null;
-- Autocomplete: word similarity (<%) on the names of places that have at least one active hotel.
create index destination_autocomplete on destinations using gin (normalized_name gin_trgm_ops)
    where deleted_at is null and hotel_count > 0;
create index destinations_featured_rank_idx on destinations (featured_rank) where featured_rank is not null;
