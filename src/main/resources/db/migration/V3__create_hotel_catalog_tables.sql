-- Hotel catalog used by the homepage (search, destinations). Table and column names follow
-- DATABASE-SCHEMA.md; ids, version and audit timestamps follow this project (see V2). Enum-like
-- columns are varchar + CHECK holding the Java enum names. Foreign keys to tables that do not exist
-- yet (currencies, ...) are added by the migration that creates those tables.

-- Both are "trusted" extensions since PostgreSQL 13: the database owner can create them without superuser.
create extension if not exists unaccent;
create extension if not exists pg_trgm;

-- Accent-, case- and spacing-insensitive form of a name: norm('  Đà  Nẵng ') = 'da nang'.
-- The only normalizer in the system: search, autocomplete and the destination sync all call it.
-- Immutable so indexes and generated columns can use it; passing the dictionary explicitly is what
-- makes unaccent safe to treat as immutable.
create function norm(value text) returns text
    language sql immutable parallel safe strict
    return lower(regexp_replace(btrim(public.unaccent('public.unaccent'::regdictionary, value)), '\s+', ' ', 'g'));

create table accommodation_types (
    id         bigint generated by default as identity primary key,
    code       varchar(30) not null,
