-- Bookings made from one cart group (C-BOOK-01..06) and the discount codes they can use (C-BOOK-03). Table and column
-- names follow DATABASE-SCHEMA.md; ids, version and audit timestamps follow this project (see V2), and enum-like
-- columns hold the Java enum names. Currency columns get their foreign key with the currencies table.

-- Codes are stored lowercased and matched case-insensitively. Money amounts (a fixed value, the minimum spend and the
-- cap) are in the code's currency, so a code with any of them needs one. Admins create codes in A-DISC-01; until
-- then they are written by SQL.
create table discount_codes (
    id                    bigint generated by default as identity primary key,
    code                  varchar(50)    not null check (code = lower(code)),
    description           varchar(500),
    discount_type         varchar(10)    not null check (discount_type in ('PERCENT', 'FIXED')),
    value                 numeric(12, 2) not null check (value > 0), -- percent, or major units for FIXED
    currency              varchar(3) check (currency ~ '^[A-Z]{3}$'),
    max_discount_minor    bigint check (max_discount_minor > 0),
    min_spend_minor       bigint check (min_spend_minor >= 0),       -- room subtotal before the discount
    starts_at             timestamptz    not null,
    ends_at               timestamptz    not null,
    usage_limit_total     integer check (usage_limit_total >= 1),     -- null = no limit
    usage_limit_per_user  integer check (usage_limit_per_user >= 1),
    first_booking_only    boolean        not null default false,
    funded_by             varchar(10)    not null default 'PLATFORM' check (funded_by in ('PLATFORM', 'HOTEL', 'SHARED')),
    applies_to_all_hotels boolean        not null default true,       -- false = only discount_code_hotels
    is_active             boolean        not null default true,
    created_by            bigint references users (id),
    deleted_at            timestamptz,                                -- soft delete: redemptions keep pointing here
    version               bigint         not null default 0,
    created_at            timestamptz    not null,
    updated_at            timestamptz    not null,
    constraint uk_discount_codes_code unique (code),
    check (ends_at > starts_at),
    check ((discount_type = 'PERCENT' and value <= 100) or (discount_type = 'FIXED' and currency is not null)),
    check ((min_spend_minor is null and max_discount_minor is null) or currency is not null)
);

create table discount_code_hotels (
    discount_code_id bigint not null references discount_codes (id) on delete cascade,
    hotel_id         bigint not null references hotels (id) on delete cascade,
    primary key (discount_code_id, hotel_id)
);

-- One hotel, one date range, one or more rooms (booking_rooms), paid once. Money is in the hotel's currency:
-- total = subtotal - discount + taxes added on top + fees. A Pending booking holds its rooms in room_inventory until
-- hold_expires_at. Status changes follow the lifecycle below, enforced and logged by the triggers.
create table bookings (
    id                     bigint generated by default as identity primary key,
    reference              varchar(12)    not null,                   -- "HB" + 8 characters
    user_id                bigint         not null references users (id),
    hotel_id               bigint         not null references hotels (id),
    check_in               date           not null,
    check_out              date           not null,
    nights                 smallint generated always as (cast(check_out - check_in as smallint)) stored,
    status                 varchar(20)    not null default 'PENDING' check (status in ('PENDING', 'CONFIRMED',
        'CHECKED_IN', 'CHECKED_OUT', 'CANCELLED', 'EXPIRED', 'NO_SHOW')),
    booker_name            varchar(100)   not null,
    booker_email           varchar(254)   not null,                   -- stored lowercased, like users.email
    booker_phone           varchar(30)    not null,
    booker_country         varchar(2) check (booker_country ~ '^[A-Z]{2}$'),
    guest_name             varchar(100),                              -- when booking for someone else
    special_requests       varchar(1000),                             -- not guaranteed
    estimated_arrival      time,                                      -- hotel's wall-clock time
    terms_accepted_at      timestamptz    not null,
    currency               varchar(3)     not null check (currency ~ '^[A-Z]{3}$'),
    subtotal_minor         bigint         not null check (subtotal_minor >= 0),
    discount_minor         bigint         not null default 0 check (discount_minor >= 0),
    tax_minor              bigint         not null default 0 check (tax_minor >= 0), -- taxes added on top
    fee_minor              bigint         not null default 0 check (fee_minor >= 0),
    total_minor            bigint         not null,
    display_currency       varchar(3) check (display_currency ~ '^[A-Z]{3}$'),
    display_total_minor    bigint,
    fx_rate                numeric(20, 10),
    discount_code_id       bigint references discount_codes (id),
    commission_rate        numeric(5, 2)  not null check (commission_rate between 0 and 100), -- the partner's, copied
    commission_minor       bigint         not null default 0,
    hold_expires_at        timestamptz,
    confirmed_at           timestamptz,
    checked_in_at          timestamptz,
    checked_out_at         timestamptz,
    cancelled_at           timestamptz,
    cancelled_by           bigint references users (id),
    cancel_reason          varchar(500),
    cancellation_fee_minor bigint,
    version                bigint         not null default 0,
    created_at             timestamptz    not null,
    updated_at             timestamptz    not null,
    constraint uk_bookings_reference unique (reference),
    check (check_out > check_in),
    check (discount_minor <= subtotal_minor),
    check (total_minor = subtotal_minor - discount_minor + tax_minor + fee_minor),
    check (status not in ('CONFIRMED', 'CHECKED_IN', 'CHECKED_OUT') or confirmed_at is not null),
    check (status not in ('CHECKED_IN', 'CHECKED_OUT') or checked_in_at is not null),
    check (status <> 'CHECKED_OUT' or checked_out_at is not null),
    check (status <> 'CANCELLED' or cancelled_at is not null),
    check (status <> 'PENDING' or hold_expires_at is not null)
);

create index bookings_hotel_id_check_in_idx on bookings (hotel_id, check_in);
create index bookings_hotel_id_status_created_at_idx on bookings (hotel_id, status, created_at);
create index bookings_user_id_check_in_idx on bookings (user_id, check_in desc);
-- The expiry job looks for Pending bookings whose hold has passed.
create index pending_holds on bookings (hold_expires_at) where status = 'PENDING';

-- One row per room booked (3 rooms = 3 rows), with what was sold copied from the room type and rate plan, so later
-- edits to them don't change the booking. cancellation_policy = {name, refundable, rules: [...]}.
create table booking_rooms (
    id                  bigint generated by default as identity primary key,
    booking_id          bigint       not null references bookings (id) on delete cascade,
    room_type_id        bigint       not null references room_types (id),
    rate_plan_id        bigint       not null references rate_plans (id),
    room_name           varchar(150) not null,
    board_type_code     varchar(10)  not null,
    cancellation_policy jsonb        not null,
    adults              smallint     not null check (adults >= 1),
    children            smallint     not null default 0 check (children >= 0),
    child_ages          smallint[]   not null default '{}', -- sorted
    lead_guest_name     varchar(100),
    total_minor         bigint       not null check (total_minor >= 0), -- this room, whole stay
    status              varchar(10)  not null default 'ACTIVE' check (status in ('ACTIVE', 'CANCELLED')),
    cancelled_at        timestamptz,
    version             bigint       not null default 0,
    created_at          timestamptz  not null,
    updated_at          timestamptz  not null,
    check (cardinality(child_ages) = children),
    check (0 <= all (child_ages) and 17 >= all (child_ages))
);

create index booking_rooms_booking_id_idx on booking_rooms (booking_id);
create index booking_rooms_room_type_id_idx on booking_rooms (room_type_id);

-- Each night's price of a booked room. Written with its room, so it keeps the schema's composite key.
create table booking_room_nights (
    booking_room_id bigint not null references booking_rooms (id) on delete cascade,
    stay_date       date   not null,
    price_minor     bigint not null check (price_minor >= 0),
    primary key (booking_room_id, stay_date)
);

create index booking_room_nights_stay_date_idx on booking_room_nights (stay_date);

-- The taxes charged, copied from tax_rules so a booking keeps the rate it was charged.
create table booking_taxes (
    id           bigint generated by default as identity primary key,
    booking_id   bigint       not null references bookings (id) on delete cascade,
    tax_rule_id  bigint references tax_rules (id),
    name         varchar(100) not null,
    is_included  boolean      not null, -- already inside the room price, not added to the total
    amount_minor bigint       not null check (amount_minor >= 0),
    version      bigint       not null default 0,
    created_at   timestamptz  not null,
    updated_at   timestamptz  not null
);

create index booking_taxes_booking_id_idx on booking_taxes (booking_id);

-- Every status change, written only by the bookings_status_log triggers and never changed, so it has no version or
-- updated_at. changed_by null = the system.
create table booking_status_history (
    id          bigint generated by default as identity primary key,
    booking_id  bigint      not null references bookings (id) on delete cascade,
    from_status varchar(20) check (from_status in ('PENDING', 'CONFIRMED', 'CHECKED_IN', 'CHECKED_OUT', 'CANCELLED',
        'EXPIRED', 'NO_SHOW')),
    to_status   varchar(20) not null check (to_status in ('PENDING', 'CONFIRMED', 'CHECKED_IN', 'CHECKED_OUT',
        'CANCELLED', 'EXPIRED', 'NO_SHOW')),
    changed_by  bigint references users (id),
    reason      varchar(500),
    created_at  timestamptz not null default now()
);

create index booking_status_history_booking_id_idx on booking_status_history (booking_id);

-- A code used by a booking. Usage limits count these rows; an expired hold deletes its row.
create table discount_redemptions (
    id               bigint generated by default as identity primary key,
    discount_code_id bigint      not null references discount_codes (id),
    booking_id       bigint      not null references bookings (id) on delete cascade,
    user_id          bigint      not null references users (id),
    amount_minor     bigint      not null check (amount_minor > 0),
    version          bigint      not null default 0,
    created_at       timestamptz not null,
    updated_at       timestamptz not null,
    constraint uk_discount_redemptions_booking_id unique (booking_id)
);

create index discount_redemptions_discount_code_id_user_id_idx on discount_redemptions (discount_code_id, user_id);

