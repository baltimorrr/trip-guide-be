alter table reviews add constraint fk_reviews_booking_id foreign key (booking_id) references bookings (id);

-- The booking lifecycle (USER_STORIES §7):
-- PENDING -> CONFIRMED -> CHECKED_IN -> CHECKED_OUT; PENDING -> CANCELLED or EXPIRED; CONFIRMED -> CANCELLED or NO_SHOW.
-- A booking starts PENDING, and any other change is refused. Hibernate writes every column on update, so an update
-- that keeps the status passes.
create function booking_status_check() returns trigger
    language plpgsql as $$
begin
    if tg_op = 'INSERT' then
        if new.status <> 'PENDING' then
            raise exception 'A booking starts as PENDING, not %', new.status using errcode = 'check_violation';
        end if;
    elsif new.status is distinct from old.status
        and (old.status, new.status) not in (('PENDING', 'CONFIRMED'), ('PENDING', 'CANCELLED'), ('PENDING', 'EXPIRED'),
                                             ('CONFIRMED', 'CHECKED_IN'), ('CONFIRMED', 'CANCELLED'),
                                             ('CONFIRMED', 'NO_SHOW'), ('CHECKED_IN', 'CHECKED_OUT')) then
        raise exception 'A booking can''t go from % to %', old.status, new.status using errcode = 'check_violation';
    end if;
    return new;
end
$$;

-- Logs a status change. Who and why come from transaction-local settings (set_config(name, value, true)):
-- app.changed_by (a user id) and app.status_reason. Without app.changed_by, the booking's own user made a new booking
-- and the system made any later change.
create function booking_status_log() returns trigger
    language plpgsql as $$
begin
    insert into booking_status_history (booking_id, from_status, to_status, changed_by, reason, created_at)
    values (new.id, case when tg_op = 'UPDATE' then old.status end, new.status,
            coalesce(cast(nullif(current_setting('app.changed_by', true), '') as bigint),
                     case when tg_op = 'INSERT' then new.user_id end),
            nullif(current_setting('app.status_reason', true), ''), now());
    return null;
end
$$;

create trigger bookings_status_check
    before insert or update of status on bookings
    for each row execute function booking_status_check();

create trigger bookings_status_log_insert
    after insert on bookings
    for each row execute function booking_status_log();

create trigger bookings_status_log_update
    after update of status on bookings
    for each row when (old.status is distinct from new.status) execute function booking_status_log();
