-- Hotel policies (C-HOTEL-03) and customer reviews (C-HOTEL-07), read by the hotel detail page. Table and column
-- names follow DATABASE-SCHEMA.md; ids, version and audit timestamps follow this project (see V2). Enum-like columns
-- hold the Java enum names.

-- What a guest should know before arriving, one paragraph per row. Check-in/out times and the minimum check-in age
-- are columns of hotels.
create table hotel_policies (
    id          bigint generated by default as identity primary key,
    hotel_id    bigint      not null references hotels (id) on delete cascade,
    policy_type varchar(20) not null
        check (policy_type in ('CHILDREN', 'EXTRA_BED', 'PETS', 'SMOKING', 'DEPOSIT', 'PAYMENT', 'OTHER')),
    description text        not null,
    sort_order  smallint    not null default 0,
    version     bigint      not null default 0,
    created_at  timestamptz not null,
    updated_at  timestamptz not null
);

create index hotel_policies_hotel_id_idx on hotel_policies (hotel_id);

-- One review per stay. booking_id gets its foreign key to bookings in the migration that creates that table; until
-- then nothing writes reviews (C-MYBK-05). No cascades: the schema keeps reviews when a hotel or user row goes.
create table reviews (
    id               bigint generated by default as identity primary key,
    booking_id       bigint      not null,
    hotel_id         bigint      not null references hotels (id),
    user_id          bigint      not null references users (id),
    score            smallint    not null check (score between 1 and 10),
    title            varchar(200),
    body             text,
    traveller_type   varchar(20) check (traveller_type in ('SOLO', 'COUPLE', 'FAMILY', 'BUSINESS', 'GROUP')),
    status           varchar(20) not null default 'PUBLISHED' check (status in ('PUBLISHED', 'HIDDEN')),
    owner_reply      text,
    owner_replied_at timestamptz,
    version          bigint      not null default 0,
    created_at       timestamptz not null,
    updated_at       timestamptz not null,
    constraint uk_reviews_booking_id unique (booking_id)
);

-- The hotel page lists published reviews, newest first.
create index reviews_hotel_id_created_at_idx on reviews (hotel_id, created_at desc) where status = 'PUBLISHED';
