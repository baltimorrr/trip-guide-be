-- SQL twin of FreeCancellation.until in the Java code; change both. The moment cancelling a booking of this policy
-- stops being free, or null when the policy is not refundable. Check-in is check_in_from on the check-in day in the
-- hotel's zone; a rule "less than N hours before check-in costs a penalty" ends the free period N hours before, and the
-- largest N with a penalty wins. Subtracting a pure-hours interval from a timestamptz works on the instant timeline, as
-- ZonedDateTime.minusHours does. Callers compare the result with their own "now". A check-in time inside an autumn
-- daylight-saving overlap may get a different offset than Java picks; check-in times are in the afternoon.
create function free_cancellation_until(policy_id bigint, check_in date, check_in_from time, zone text)
    returns timestamptz
    language sql stable parallel safe
    return (select ((check_in + check_in_from) at time zone zone)
                   - make_interval(hours => coalesce((select max(r.hours_before_check_in)
                                                      from cancellation_policy_rules r
                                                      where r.policy_id = cp.id and r.penalty_value > 0), 0))
            from cancellation_policies cp
            where cp.id = policy_id and cp.is_refundable);
