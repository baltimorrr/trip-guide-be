-- free-cancellation rule. Table and column names follow DATABASE-SCHEMA.md; ids, version and audit timestamps follow
-- this project (see V2). Enum-like columns hold the Java enum names. The link tables keep the schema's composite keys
-- without id/version, like user_roles.

-- Things a hotel offers (scope HOTEL: "services and facilities") or a room has (scope ROOM: "room features").
create table amenities (
    id         bigint generated by default as identity primary key,
    code       varchar(50)  not null,
    name       varchar(100) not null,
    group_name varchar(60)  not null, -- General, Wellness, Bathroom...
    scope      varchar(10)  not null check (scope in ('HOTEL', 'ROOM')),
    icon       varchar(50),
    version    bigint       not null default 0,
    created_at timestamptz  not null,
    updated_at timestamptz  not null,
    constraint uk_amenities_code unique (code)
);

