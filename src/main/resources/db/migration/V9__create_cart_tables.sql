-- Each signed-in customer's cart (C-CART-01..04). Guests keep their cart in the browser and merge it into their
-- account on sign-in, so unlike the original schema there is no guest_token and user_id is required. Table and column
-- names follow DATABASE-SCHEMA.md. currency gets its foreign key with the currencies table.
create table carts (
    id         bigint generated by default as identity primary key,
    user_id    bigint      not null unique references users (id) on delete cascade,
    version    bigint      not null default 0,
    created_at timestamptz not null,
    updated_at timestamptz not null
);

-- A cart holds lines of any hotel and dates; the hotel comes from the rate plan. Lines of one hotel with the same
-- check_in and check_out are checked out together as one booking. Prices are re-calculated on every read:
-- price_at_add_minor only feeds the "price changed" notice.
create table cart_items (
    id                 bigint generated by default as identity primary key,
    cart_id            bigint      not null references carts (id) on delete cascade,
    rate_plan_id       bigint      not null references rate_plans (id) on delete cascade,
    check_in           date        not null,
    check_out          date        not null,
    quantity           smallint    not null default 1 check (quantity >= 1), -- rooms
    adults             smallint    not null check (adults >= 1),            -- per room
    children           smallint    not null default 0 check (children >= 0),
    child_ages         smallint[]  not null default '{}',                   -- per room, sorted
    price_at_add_minor bigint      not null check (price_at_add_minor >= 0), -- one room, whole stay
    currency           varchar(3)  not null check (currency ~ '^[A-Z]{3}$'),
    version            bigint      not null default 0,
    created_at         timestamptz not null,
    updated_at         timestamptz not null,
    check (check_out > check_in),
    check (cardinality(child_ages) = children),
    check (0 <= all (child_ages) and 17 >= all (child_ages))
);

-- One line per rate, stay and guests (the ages are stored sorted). It also serves lookups by cart.
create unique index cart_items_line_key on cart_items (cart_id, rate_plan_id, check_in, check_out, adults, child_ages);

-- The expiry job deletes by check-in.
create index cart_items_check_in_idx on cart_items (check_in);
