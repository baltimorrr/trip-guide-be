-- Email verification, password reset, refresh-token sessions, sign-in lockout and profile fields. Table and
-- column names follow DATABASE-SCHEMA.md; ids, version and audit timestamps follow this project (see V2).

alter table users
    add column phone                 varchar(30),
    add column country_code          varchar(2) check (country_code ~ '^[A-Z]{2}$'),       -- nationality, ISO 3166
    add column preferred_currency    varchar(3) check (preferred_currency ~ '^[A-Z]{3}$'), -- ISO 4217; FK added with currencies
    add column email_verified_at     timestamptz,
    add column failed_login_count    smallint not null default 0 check (failed_login_count >= 0),
    add column first_failed_login_at timestamptz, -- start of the current lockout window
    add column locked_until          timestamptz;

-- Accounts created before email verification existed keep signing in.
update users set email_verified_at = created_at;

-- One-time links sent by email. Only the SHA-256 of the token is stored.
create table user_tokens (
    id         bigint generated by default as identity primary key,
    user_id    bigint      not null references users (id) on delete cascade,
    type       varchar(20) not null check (type in ('EMAIL_VERIFY', 'PASSWORD_RESET')),
    token_hash varchar(64) not null,
    expires_at timestamptz not null,
    used_at    timestamptz,
    version    bigint      not null default 0,
    created_at timestamptz not null,
    updated_at timestamptz not null,
    constraint uk_user_tokens_token_hash unique (token_hash)
);

create index user_tokens_user_id_type_idx on user_tokens (user_id, type);

-- One row per sign-in (device). The refresh token rotates on every use; the hash it replaced is kept so a
-- replayed old token can be detected and the session revoked. Only SHA-256 hashes are stored.
create table user_sessions (
    id                  bigint generated by default as identity primary key,
    user_id             bigint       not null references users (id) on delete cascade,
    refresh_token_hash  varchar(64)  not null,
    previous_token_hash varchar(64),
    user_agent          varchar(500),
    ip                  varchar(45), -- textual IPv4 or IPv6
    expires_at          timestamptz  not null, -- fixed at sign-in; rotation does not extend it
    last_used_at        timestamptz,
    revoked_at          timestamptz,
    version             bigint       not null default 0,
    created_at          timestamptz  not null,
    updated_at          timestamptz  not null,
    constraint uk_user_sessions_refresh_token_hash unique (refresh_token_hash)
);

create index user_sessions_user_id_idx on user_sessions (user_id);
create index user_sessions_previous_token_hash_idx on user_sessions (previous_token_hash);
