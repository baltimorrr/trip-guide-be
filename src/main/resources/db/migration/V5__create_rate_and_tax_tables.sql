       ('BB', 'Breakfast included', now(), now()),
       ('HB', 'Half board', now(), now()),
       ('FB', 'Full board', now(), now()),
       ('AI', 'All inclusive', now(), now());

create table cancellation_policies (
    id            bigint generated by default as identity primary key,
    hotel_id      bigint references hotels (id) on delete cascade, -- null = platform template
    name          varchar(150) not null,                           -- "Free until 48h before"
    is_refundable boolean      not null,
    version       bigint       not null default 0,
    created_at    timestamptz  not null,
    updated_at    timestamptz  not null
);

create index cancellation_policies_hotel_id_idx on cancellation_policies (hotel_id);

-- "Cancelled less than hours_before_check_in hours before check-in costs the penalty". The rule that applies is
-- the one with the smallest hours_before_check_in still greater than the hours left. Non-refundable = one rule
-- with a huge number of hours.
create table cancellation_policy_rules (
    id                    bigint generated by default as identity primary key,
    policy_id             bigint         not null references cancellation_policies (id) on delete cascade,
    hours_before_check_in integer        not null check (hours_before_check_in >= 0),
    penalty_type          varchar(10)    not null check (penalty_type in ('PERCENT', 'NIGHTS', 'FIXED')),
    penalty_value         numeric(12, 2) not null check (penalty_value >= 0),
    version               bigint         not null default 0,
    created_at            timestamptz    not null,
    updated_at            timestamptz    not null,
    constraint uk_cancellation_policy_rules_policy_id_hours unique (policy_id, hours_before_check_in)
);

-- One way of selling a room type: board, cancellation policy and base price per room per night.
create table rate_plans (
    id                     bigint generated by default as identity primary key,
    room_type_id           bigint       not null references room_types (id) on delete cascade,
    name                   varchar(150) not null, -- "Breakfast included, free cancellation"
    board_type_id          bigint       not null references board_types (id),
    cancellation_policy_id bigint       not null references cancellation_policies (id),
    base_price_minor       bigint       not null check (base_price_minor >= 0), -- per room per night
    currency               varchar(3)   not null check (currency ~ '^[A-Z]{3}$'),
    min_nights             smallint     not null default 1 check (min_nights >= 1),
    is_active              boolean      not null default true,
    deleted_at             timestamptz,
    version                bigint       not null default 0,
    created_at             timestamptz  not null,
    updated_at             timestamptz  not null
);

create index rate_plans_room_type_id_idx on rate_plans (room_type_id) where is_active and deleted_at is null;

-- The owner's price for one date, winning over rules and the base price. Written only by set-based SQL, so it
-- keeps the schema's composite key (like room_inventory).
create table rate_plan_prices (
    rate_plan_id bigint      not null references rate_plans (id) on delete cascade,
    stay_date    date        not null,
    price_minor  bigint      not null check (price_minor >= 0),
    min_nights   smallint check (min_nights >= 1), -- null = the plan's min_nights
    is_closed    boolean     not null default false, -- this rate is not sold for the night
    updated_at   timestamptz not null default now(),
    primary key (rate_plan_id, stay_date)
);

-- Season, weekend and holiday price changes for a date range (inclusive) and weekdays.
create table rate_rules (
    id           bigint generated by default as identity primary key,
    rate_plan_id bigint       not null references rate_plans (id) on delete cascade,
    name         varchar(100) not null, -- "Summer high season", "Weekend", "Tet"
    date_from    date         not null,
    date_to      date         not null,
    days_of_week smallint[],            -- ISO 1 = Monday ... 7 = Sunday; null = every day
    adjustment   varchar(10)  not null check (adjustment in ('SET_PRICE', 'PERCENT', 'AMOUNT')),
    amount_minor bigint,                -- SET_PRICE: the price; AMOUNT: +/- change
    percent      numeric(6, 2),         -- PERCENT: +20.00 or -15.00
    priority     smallint     not null default 0, -- higher wins when rules overlap
    is_active    boolean      not null default true,
    version      bigint       not null default 0,
    created_at   timestamptz  not null,
    updated_at   timestamptz  not null,
    check (date_to >= date_from),
    check (days_of_week is null
        or (cardinality(days_of_week) > 0 and days_of_week <@ array[1, 2, 3, 4, 5, 6, 7]::smallint[])),
    check ((adjustment = 'SET_PRICE' and amount_minor >= 0 and percent is null)
        or (adjustment = 'AMOUNT' and amount_minor is not null and percent is null)
        or (adjustment = 'PERCENT' and percent > -100 and amount_minor is null))
);

create index rate_rules_rate_plan_id_date_from_date_to_idx on rate_rules (rate_plan_id, date_from, date_to)
    where is_active;

-- Taxes by country only (e.g. VAT in VN). A new rate is a new row with new validity dates, so past bookings keep
-- the rate they were charged. Hotel service charges are not tax rules: they are inside the room price.
create table tax_rules (
    id                     bigint generated by default as identity primary key,
    country_code           varchar(2)     not null check (country_code ~ '^[A-Z]{2}$'),
    name                   varchar(100)   not null, -- "VAT"
    calc_type              varchar(20)    not null
        check (calc_type in ('PERCENT', 'PER_NIGHT', 'PER_BOOKING', 'PER_PERSON_NIGHT')),
    value                  numeric(12, 4) not null check (value > 0), -- percent, or an amount for fixed types
    currency               varchar(3) check (currency ~ '^[A-Z]{3}$'), -- fixed types only
    is_included            boolean        not null default false,     -- already inside the room price?
    applies_after_discount boolean        not null default true,      -- percent only
    valid_from             date,                                      -- null = no start limit
    valid_to               date,                                      -- null = no end limit (inclusive)
    is_active              boolean        not null default true,
    version                bigint         not null default 0,
    created_at             timestamptz    not null,
    updated_at             timestamptz    not null,
    check (calc_type <> 'PERCENT' or value <= 100),
    check ((calc_type = 'PERCENT') = (currency is null)),
    check (valid_to is null or valid_from is null or valid_to >= valid_from)
);

create index tax_rules_country_code_idx on tax_rules (country_code) where is_active;

-- Price of one night of a rate plan, in the plan's minor units. The only definition of a night's price
-- (search now, cart and booking later); the first match wins:
-- 1. the rate_plan_prices row for that date (the owner's override)
-- 2. the active rate_rules row with the highest priority, then the newest, covering the date and its ISO weekday
-- 3. rate_plans.base_price_minor
-- Closed dates and minimum stays are not prices: callers read them from rate_plan_prices. Percent changes round
-- half away from zero to whole minor units; an amount change never goes below 0.
create function night_price(plan_id bigint, night date) returns bigint
    language sql stable parallel safe
    return coalesce(
        (select p.price_minor from rate_plan_prices p where p.rate_plan_id = plan_id and p.stay_date = night),
        (select case r.adjustment
                    when 'SET_PRICE' then r.amount_minor
                    when 'AMOUNT' then greatest(rp.base_price_minor + r.amount_minor, 0)
                    else round(rp.base_price_minor * (100 + r.percent) / 100)::bigint end
         from rate_rules r
         join rate_plans rp on rp.id = r.rate_plan_id
         where r.rate_plan_id = plan_id and r.is_active and night between r.date_from and r.date_to
           and (r.days_of_week is null or extract(isodow from night)::smallint = any (r.days_of_week))
         order by r.priority desc, r.id desc
         limit 1),
        (select rp.base_price_minor from rate_plans rp where rp.id = plan_id));
