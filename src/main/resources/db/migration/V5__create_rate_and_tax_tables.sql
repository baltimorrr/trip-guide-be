-- Rate plans, board types, cancellation policies, per-date prices, season/weekend rules and tax rules, read by
-- the hotel search to price a stay (C-SRCH-01). Table and column names follow DATABASE-SCHEMA.md; ids, version
-- and audit timestamps follow this project (see V2). Enum-like columns hold the Java enum names. Currency
-- columns get their foreign key to currencies in the migration that creates that table.

create table board_types (
    id         bigint generated by default as identity primary key,
    code       varchar(10) not null,
    name       varchar(60) not null,
    version    bigint      not null default 0,
    created_at timestamptz not null,
    updated_at timestamptz not null,
    constraint uk_board_types_code unique (code)
);

