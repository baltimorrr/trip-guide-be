-- Application users. Emails are stored lowercased by the application, so a plain unique
-- constraint is enough to make them case-insensitively unique.
create table users (
    id            bigint generated by default as identity primary key,
    email         varchar(254) not null,
    password_hash varchar(100) not null, -- "{bcrypt}" prefix + 60-char hash
    full_name     varchar(100) not null,
    enabled       boolean      not null default true,
    version       bigint       not null default 0,
    created_at    timestamptz  not null,
    updated_at    timestamptz  not null,
    constraint uk_users_email unique (email)
);

create table user_roles (
    user_id bigint      not null references users (id) on delete cascade,
    role    varchar(20) not null,
    primary key (user_id, role)
);
