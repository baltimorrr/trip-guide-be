package com.company.project.destination.repository.impl;

import com.company.project.destination.repository.DestinationSyncRepository;
import com.company.project.hotel.repository.HotelJpql;
import com.company.project.hotel.repository.HotelSql;
import jakarta.persistence.EntityManager;
import lombok.RequiredArgsConstructor;
import org.springframework.stereotype.Repository;

/**
 * The destination sync's statements. The count refresh is JPQL. The lock, the insert and the spelling refresh
 * are native SQL: JPQL has no advisory locks, and the other two need {@code mode()}, a window over the slugs and
 * {@code ON CONFLICT} on a partial index.
 */
@Repository
@RequiredArgsConstructor
public class DestinationSyncRepositoryImpl implements DestinationSyncRepository {

	private static final String LOCK = "select 1 from pg_advisory_xact_lock(hashtext('destination_sync'))";

	/**
	 * Every country / city / district / ward used by a listed hotel: its keys (norm() of the address parts) and
	 * the most common spelling of each part. A spelling is chosen once per place and reused by the places inside
	 * it, so a ward never spells its city differently from the city's own row. Each spelling normalizes to its
	 * place's key, so writing one never moves a row to another place.
	 */
	private static final String PLACES = """
			with hotel_places as (
			    select a.country_code,
			           coalesce(norm(a.state_province), '') as province_key,
			           coalesce(norm(a.city), '') as city_key,
			           coalesce(norm(a.district), '') as district_key,
			           coalesce(norm(a.ward), '') as ward_key,
			           btrim(a.state_province) as state_province, btrim(a.city) as city,
			           btrim(a.district) as district, btrim(a.ward) as ward
			    from hotels h
			    join addresses a on a.id = h.address_id
			    where\s""" + HotelSql.HOTEL_LISTED + """

			),
			provinces as (
			    select country_code, province_key, mode() within group (order by state_province) as state_province
			    from hotel_places
			    where province_key <> ''
			    group by country_code, province_key
			),
			cities as (
			    select country_code, province_key, city_key, mode() within group (order by city) as city
			    from hotel_places
			    group by country_code, province_key, city_key
			),
			districts as (
			    select country_code, province_key, city_key, district_key,
			           mode() within group (order by district) as district
			    from hotel_places
			    where district_key <> ''
			    group by country_code, province_key, city_key, district_key
			),
			wards as (
			    select country_code, province_key, city_key, district_key, ward_key,
			           mode() within group (order by ward) as ward
			    from hotel_places
			    where ward_key <> ''
			    group by country_code, province_key, city_key, district_key, ward_key
			),
			places as (
			    select 'COUNTRY' as type, country_code, '' as province_key, '' as city_key, '' as district_key,
			           '' as ward_key, null as state_province, null as city, null as district, null as ward
			    from hotel_places
			    group by country_code
			    union all
			    select 'CITY', country_code, province_key, city_key, '', '', p.state_province, c.city, null, null
			    from cities c
			    left join provinces p using (country_code, province_key)
			    union all
			    select 'DISTRICT', country_code, province_key, city_key, district_key, '', p.state_province, c.city,
			           d.district, null
			    from districts d
			    join cities c using (country_code, province_key, city_key)
			    left join provinces p using (country_code, province_key)
			    union all
			    select 'WARD', country_code, province_key, city_key, district_key, ward_key, p.state_province, c.city,
			           d.district, w.ward
			    from wards w
			    join cities c using (country_code, province_key, city_key)
			    left join districts d using (country_code, province_key, city_key, district_key)
			    left join provinces p using (country_code, province_key)
			)""";

	/**
	 * The display name is the spelling of the place's own level, a country's its ISO code until it is named.
	 * Slugs are built from the keys ({@code vn-da-nang-hai-chau}); a short hash of the full key is appended only
	 * when another place already has, or in this batch would get, the same slug (e.g. one city name in two
	 * provinces). The keys themselves are generated by the table.
	 */
	private static final String INSERT_NEW_PLACES = PLACES + """
			,
			slugged as (
			    select p.*,
			           rtrim(lower(p.country_code) || '-' || btrim(regexp_replace(
			               concat_ws(' ', nullif(p.city_key, ''), nullif(p.district_key, ''), nullif(p.ward_key, '')),
			               '[^a-z0-9]+', '-', 'g'), '-'), '-') as base_slug
			    from places p
			)
			insert into destinations (type, name, slug, country_code, state_province, city, district, ward, source,
			                          created_at, updated_at)
			select type, coalesce(ward, district, city, country_code),
			       case when count(*) over (partition by base_slug) > 1
			                 or exists (select 1 from destinations x where x.slug = s.base_slug)
			            then base_slug || '-' || left(md5(concat_ws('|', country_code, province_key, city_key,
			                                                        district_key, ward_key)), 6)
			            else base_slug end,
			       country_code, state_province, city, district, ward, 'SYNC', now(), now()
			from slugged s
			on conflict (country_code, province_key, city_key, district_key, ward_key) where deleted_at is null
			do nothing""";

	private static final String REFRESH_SPELLINGS = PLACES + """

			update destinations d
			set state_province = p.state_province, city = p.city, district = p.district, ward = p.ward
			from places p
			where d.deleted_at is null
			  and d.country_code = p.country_code and d.province_key = p.province_key and d.city_key = p.city_key
			  and d.district_key = p.district_key and d.ward_key = p.ward_key
			  and (d.state_province, d.city, d.district, d.ward)
			      is distinct from (p.state_province, p.city, p.district, p.ward)""";

	private static final String REFRESH_HOTEL_COUNTS = """
			update Destination d
			set d.hotelCount = (select cast(count(h) as Integer)
			                    from Hotel h
			                    join h.address a
			                    where\s""" + HotelJpql.HOTEL_LISTED + " and " + HotelJpql.ADDRESS_IN_DESTINATION + """
			),
			    d.lastSyncedAt = instant
			where d.deletedAt is null""";

	private final EntityManager entityManager;

	@Override
	public void lock() {
		entityManager.createNativeQuery(LOCK).getSingleResult();
	}

	@Override
	public int insertNewPlaces() {
		return entityManager.createNativeQuery(INSERT_NEW_PLACES).executeUpdate();
	}

	@Override
	public void refreshSpellings() {
		entityManager.createNativeQuery(REFRESH_SPELLINGS).executeUpdate();
	}

	@Override
	public void refreshHotelCounts() {
		// A bulk update bypasses the persistence context: write pending changes first, drop stale entities after.
		entityManager.flush();
		entityManager.createQuery(REFRESH_HOTEL_COUNTS).executeUpdate();
		entityManager.clear();
	}

}
