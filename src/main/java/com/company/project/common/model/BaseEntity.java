package com.company.project.common.model;

import java.time.Instant;

import jakarta.persistence.Column;
import jakarta.persistence.EntityListeners;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.MappedSuperclass;
import jakarta.persistence.Version;
import lombok.Getter;
import org.hibernate.Hibernate;
import org.springframework.data.annotation.CreatedDate;
import org.springframework.data.annotation.LastModifiedDate;
import org.springframework.data.jpa.domain.support.AuditingEntityListener;

/**
 * Common columns for every table: identity id, optimistic-lock version, and audit timestamps.
 * The timestamps are filled by Spring Data auditing, enabled in {@code JpaAuditingConfig}.
 * <p>
 * Matching SQL for each table:
 * {@code id bigint generated by default as identity primary key, version bigint not null,
 * created_at timestamptz not null, updated_at timestamptz not null}.
 */
@MappedSuperclass
@EntityListeners(AuditingEntityListener.class)
@Getter
public abstract class BaseEntity {

	@Id
	@GeneratedValue(strategy = GenerationType.IDENTITY)
	private Long id;

	@Version
	@Column(nullable = false)
	private Long version;

	@CreatedDate
	@Column(name = "created_at", nullable = false, updatable = false)
	private Instant createdAt;

	@LastModifiedDate
	@Column(name = "updated_at", nullable = false)
	private Instant updatedAt;

	// Entities are equal only when both are persisted with the same id. Hibernate.getClass
	// unwraps lazy proxies so a proxy and its real entity compare equal.
	@Override
	public boolean equals(Object other) {
		if (this == other) {
			return true;
		}
		if (other == null || Hibernate.getClass(this) != Hibernate.getClass(other)) {
			return false;
		}
		return id != null && id.equals(((BaseEntity) other).id);
	}

	// Constant per class so the hash code does not change when the id is assigned on persist.
	@Override
	public int hashCode() {
		return Hibernate.getClass(this).hashCode();
	}

}
